"""Directional-effects register: every arm vs ITS OWN control in the same experiment, on per-attempt mechanism
metrics, task-paired (per task: arm mean - control mean; averaged over tasks both arms ran). Purpose: find small
shifts that point the right way and were discarded because solve rate missed a single-run threshold, so they can be
stacked (e.g. in a multi-pattern LoRA) and re-tested together.

Direction convention: "good" = higher solve / first_gold / convert, lower wrong_file / overflow / no_edit /
recurring_wrong. A cell is marked + (good direction) or - (bad) with its z; z uses the sd of per-task deltas
(rough). Writes Outputs/DIRECTION_REGISTER.md."""
import json
import math
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, "Outputs")
db = sqlite3.connect("kb/attempts.sqlite")
CONTROLS = ("C_pack1", "base", "N_none")
GOOD_UP = {"solve": 1, "first_gold": 1, "convert": 1, "wrong_file": -1, "overflow": -1, "no_edit": -1}
rows = db.execute("""
    SELECT a.exp, a.arm, a.task, a.resolved, a.error_class, f.first_edit_gold, f.edited_any_gold, f.n_edit_ok
    FROM attempts_unique a JOIN attempt_features f ON f.attempt_id = a.id AND f.basis = 'trace'
    WHERE a.model NOT LIKE '%31b%' AND a.resolved IS NOT NULL""").fetchall()
data = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))  # exp -> arm -> task -> [metric dicts]
for exp, arm, task, res, ec, feg, eag, nok in rows:
    m = {"solve": res, "first_gold": int(bool(feg)), "wrong_file": int(bool(nok) and not eag),
         "overflow": int(ec == "overflow"), "no_edit": int(not nok)}
    if feg:
        m["convert"] = res
    data[exp][arm][task].append(m)
changes = {(e, a): c for e, a, c in db.execute("SELECT exp, arm, changed_vs_pack1 FROM arm_catalog")}


def paired(arm_tasks, ctl_tasks, key):
    deltas = []
    for task in set(arm_tasks) & set(ctl_tasks):
        a = [m[key] for m in arm_tasks[task] if key in m]
        c = [m[key] for m in ctl_tasks[task] if key in m]
        if a and c:
            deltas.append(sum(a) / len(a) - sum(c) / len(c))
    if len(deltas) < 5:
        return None
    mean = sum(deltas) / len(deltas)
    sd = math.sqrt(sum((d - mean) ** 2 for d in deltas) / (len(deltas) - 1))
    return mean, (mean / (sd / math.sqrt(len(deltas))) if sd else 0.0), len(deltas)


out = []
for exp, arms in data.items():
    ctl = next((c for c in CONTROLS if c in arms), None)
    if not ctl:
        continue
    for arm, tasks in arms.items():
        if arm == ctl or arm is None:
            continue
        n = sum(len(v) for v in tasks.values())
        if n < 40:
            continue
        row = {"exp": exp, "arm": arm, "control": ctl, "n": n, "changed": changes.get((exp, arm))}
        for key in GOOD_UP:
            row[key] = paired(tasks, arms[ctl], key)
        good = [k for k in GOOD_UP if row[k] and GOOD_UP[k] * row[k][0] > 0]
        row["good_metrics"] = len(good)
        row["good_z_sum"] = round(sum(GOOD_UP[k] * row[k][1] for k in GOOD_UP if row[k]), 2)
        out.append(row)
out.sort(key=lambda r: -r["good_z_sum"])


def cell(key, v):
    if v is None:
        return "-"
    mean, z, _ = v
    sign = "+" if GOOD_UP[key] * mean > 0 else "-"
    return f"{sign}{abs(mean) * 100:.1f} (z {GOOD_UP[key] * z:+.1f})"


md = ["# Directional-effects register (arm vs its own control, task-paired)\n",
      "Generated by `Outputs/_direction_register.py`. `+` = moved in the good direction, `-` = bad; value in points; "
      "z is signed so positive = good (rough: per-task deltas, small n). `good z sum` ranks arms by combined "
      "direction across the six metrics. Single cells at |z| < 2 are hints, not findings; the point of the register "
      "is consistent direction across metrics and across replications.\n",
      "| exp | arm | vs | n | solve | first gold | convert | wrong file | overflow | no edit | good metrics | good z sum |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in out:
    md.append(f"| {r['exp']} | {r['arm']} | {r['control']} | {r['n']} | " + " | ".join(cell(k, r[k]) for k in GOOD_UP)
              + f" | {r['good_metrics']}/6 | {r['good_z_sum']:+.1f} |")
md += ["", "## What each arm changed (vs pack 1)\n"]
for r in out:
    md.append(f"- **{r['exp']} / {r['arm']}**: {r['changed'] or '(not recorded)'}")
Path("Outputs/DIRECTION_REGISTER.md").write_text("\n".join(md) + "\n", encoding="utf-8")
Path("Outputs/direction_register.json").write_text(json.dumps(out, indent=1, default=str))
print("\n".join(md[:4 + len(out)]))
