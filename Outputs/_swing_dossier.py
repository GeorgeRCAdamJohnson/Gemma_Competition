"""Per-task dossier for the swing tasks (E4B solves some attempts, not others): WHY they don't land consistently.
For every swing task (E4B attempts >= 40, solve rate 10-90%), traced or patched attempts only:
  failure taxonomy (exclusive): overflow | no_edit | wrong_file (never edited a gold file) | gold_after_wrong (first
    edit elsewhere, later reached gold) | right_file_wrong_fix (first edit gold; split by hidden-test outcome:
    contract = some NEW tests fail; regression = only pre-existing tests fail; collection = import/collection error)
  first-edit file distribution, solved vs failed (wrong-file attractors)
  fix families: winning patches and losing patches grouped by their added-line signature; top families with counts
  failing hidden tests most common among right-file failures (the contract they miss)
Writes Outputs/swing_dossier.json and Outputs/SWING_DOSSIER.md."""
import hashlib
import json
import re
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, "kb/attemptdb")
from vfs import VFS  # noqa: E402

db = sqlite3.connect("kb/attempts.sqlite")
vfs = VFS(roots=("Outputs",))
q = lambda s, *a: db.execute(s, a).fetchall()
NEW = {t: set(re.findall(r"^\+\s*(?:async\s+)?def (test_\w+)", tp, re.M)) for t, tp in q("SELECT task, test_patch FROM tasks")}
GOLD = {t: {g for g in json.loads(gf) if "test" not in g} for t, gf in q("SELECT task, gold_files FROM tasks")}
# task_rates has one row per model label; a task qualifies if any E4B label is a swing, listed once.
swing = sorted({t for t, n, r in q("""SELECT task, n, rate FROM task_rates WHERE model NOT LIKE '%31b%' AND n >= 40
                                      AND rate BETWEEN 0.1 AND 0.9""")})


def family(patch):
    adds = sorted({re.sub(r"\s+", " ", l[1:].strip()) for l in patch.splitlines()
                   if l.startswith("+") and not l.startswith("+++") and l[1:].strip()})
    files = sorted(set(re.findall(r"^\+\+\+ b/(\S+)", patch, re.M)))
    return hashlib.sha1(("|".join(files) + "||" + "\n".join(adds)).encode()).hexdigest()[:10], files, adds


def test_kind(path, task):
    if not path or not vfs.exists(path):
        return "no_test_output", []
    txt = vfs.text(path)
    if re.search(r"ERROR collecting|errors? during collection|ImportError|ModuleNotFoundError", txt):
        return "collection", []
    fails = re.findall(r"^(?:FAILED|ERROR) \S+::(\w+)", txt, re.M)
    new = [f for f in fails if f in NEW.get(task, set())]
    return ("contract" if new else "regression" if fails else "other"), (new or fails)


dossier = {}
md = ["# Swing-task dossier: why E4B lands these sometimes but not always\n",
      "Generated by `Outputs/_swing_dossier.py` from `kb/attempts.sqlite` (E4B attempts with a trace). Grading is "
      "deterministic (identical patches always get the same grade), so every miss is agent behaviour.\n"]
for task in swing:
    rows = q("""SELECT a.id, a.resolved, a.error_class, a.patch_path, a.test_output_path, f.first_edit_file,
                       f.first_edit_gold, f.edited_any_gold, f.n_edit_ok, f.n_calls, f.wall_s
                FROM attempts_unique a JOIN traces t ON t.attempt_id = a.id JOIN attempt_features f ON f.trace_id = t.trace_id
                WHERE a.task = ? AND a.model NOT LIKE '%31b%' AND a.resolved IS NOT NULL AND f.basis = 'trace'""", task)
    if len(rows) < 20:
        continue
    n, solved = len(rows), sum(r[1] for r in rows)
    tax = Counter()
    first_s, first_f = Counter(), Counter()
    fam_s, fam_f = defaultdict(list), defaultdict(list)
    failing_tests = Counter()
    solved_no_gold = 0
    for aid, res, ec, pp, tp, fe, feg, eag, nok, nc, ws in rows:
        (first_s if res else first_f)[fe or "(no edit)"] += 1
        patch = vfs.text(pp) if pp and vfs.exists(pp) else ""
        if patch.strip():
            h, files, adds = family(patch)
            (fam_s if res else fam_f)[h].append((files, adds[:6]))
        if res:
            solved_no_gold += (not eag)
            continue
        if ec == "overflow":
            k = "overflow"
        elif not nok:
            k = "no_edit"
        elif not eag:
            k = "wrong_file"
        elif not feg:
            k = "gold_after_wrong"
        else:
            kind, tests = test_kind(tp, task)
            k = f"right_file_wrong_fix:{kind}"
            failing_tests.update(tests[:3])
        tax[k] += 1
    fails = n - solved
    top_s = sorted(fam_s.values(), key=len, reverse=True)
    top_f = sorted(fam_f.values(), key=len, reverse=True)
    d = dict(task=task, attempts=n, solved=solved, solve_rate=round(solved / n, 3), gold_files=sorted(GOLD[task]),
             failure_taxonomy={k: v for k, v in tax.most_common()},
             first_edit_solved=first_s.most_common(4), first_edit_failed=first_f.most_common(5),
             winning_families=len(fam_s), top_winning_family_share=round(len(top_s[0]) / max(solved, 1), 2) if top_s else None,
             losing_families=len(fam_f), top_losing_family_share=round(len(top_f[0]) / max(fails, 1), 2) if top_f else None,
             top_losing_family=dict(files=top_f[0][0][0], added_lines=top_f[0][0][1]) if top_f else None,
             top_winning_family=dict(files=top_s[0][0][0], added_lines=top_s[0][0][1]) if top_s else None,
             common_failing_tests=failing_tests.most_common(4),
             solved_without_gold_edit=solved_no_gold,
             # if many winners never touch the gold file, "wrong_file" is not a valid failure label for this task
             gold_label_suspect=solved_no_gold > 0.25 * max(solved, 1))
    dominant = max(tax, key=tax.get) if tax else None
    d["dominant_failure"] = dominant
    dossier[task] = d
    md.append(f"## {task} — {solved}/{n} solved ({solved / n:.0%}); gold: {', '.join(sorted(GOLD[task]))}\n")
    md.append("Failures: " + ", ".join(f"{k} {v} ({v / fails:.0%})" for k, v in tax.most_common()) + "\n")
    md.append(f"First edit, solved: {first_s.most_common(3)}; failed: {first_f.most_common(4)}\n")
    md.append(f"Winning fixes: {len(fam_s)} families, top family = {d['top_winning_family_share']:.0%} of solves. "
              f"Losing fixes: {len(fam_f)} families, top = {d['top_losing_family_share'] or 0:.0%} of failures.\n")
    md.append(f"Solves that never edited a gold file: {solved_no_gold}/{solved}"
              + (" — GOLD LABEL SUSPECT: wrong_file is not a valid failure cause here.\n" if d["gold_label_suspect"] else "\n"))
    if failing_tests:
        md.append(f"Most failed hidden tests (right-file failures): {failing_tests.most_common(3)}\n")
Path("Outputs/swing_dossier.json").write_text(json.dumps(dossier, indent=1))
Path("Outputs/SWING_DOSSIER.md").write_text("\n".join(md), encoding="utf-8")

# cross-task summary
print(f"{len(dossier)} swing tasks\n")
print(f"{'task':15s} {'solve':>6s}  dominant failure            {'win fam':>7s} {'top win':>7s}  failure mix")
agg = Counter()
for t, d in sorted(dossier.items(), key=lambda kv: kv[1]["solve_rate"]):
    f = d["attempts"] - d["solved"]
    for k, v in d["failure_taxonomy"].items():
        if not d["gold_label_suspect"]:
            agg[k.split(":")[0]] += v
    mix = ", ".join(f"{k.replace('right_file_wrong_fix', 'RFWF')} {v / f:.0%}" for k, v in list(d["failure_taxonomy"].items())[:4])
    print(f"{t:15s} {d['solve_rate']:6.0%}  {str(d['dominant_failure'])[:26]:26s} {d['winning_families']:7d} "
          f"{(d['top_winning_family_share'] or 0):7.0%}  {mix}" + ("  [gold label suspect]" if d["gold_label_suspect"] else ""))
tot = sum(agg.values())
print("\nswing-task failures by cause (gold-label-suspect tasks excluded):", {k: f"{v} ({v / tot:.0%})" for k, v in agg.most_common()})
