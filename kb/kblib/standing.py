"""STANDING_TRUTHS.md (REVISION 5 R5.10 / D5-18). Generated, idempotent, <= 80 lines.

Every bullet is `- [id] statement — evidence: <path>:L<n> (<status>)`. Sources ONLY:
curated SUPPORTED claims (evidence present), SUPPORTED non-superseded log claims of
kind verdict / standing-truth, the newest unit of each correction chain, and
builder-measured facts (LB source rows, baseline banner/conflicts, runs.jsonl stack
counts, dev-harness mismatch counts, pull attribution flags, gold coverage when a
coverage file exists). Nothing is invented; nothing is adopted.
"""
from __future__ import annotations

import json
import pathlib
import re
from collections import Counter

MAX_LINES = 80
_CLOSED = re.compile(r"(?i)\b(?:dead|closed|exhausted|null|not (?:a|the) lever|regress\w*|falsified"
                     r"|dead end|not worth|underperform\w*|do not|don't|never)\b")
_OPEN = re.compile(r"(?i)\b(?:open|untested|untried|revives?|next|candidate|prerequisite"
                   r"|implication|unknown|not yet)\b")


def _one(text, n=170):
    t = " ".join((text or "").replace("**", "").replace("`", "").split())
    first = re.split(r"(?<=[.!?])\s", t, maxsplit=1)[0]
    s = first if len(first) >= 40 else t
    s = s.replace("|", "/")
    return s if len(s) <= n else s[:n - 3] + "..."


def _csv_line(path, ref):
    p = pathlib.Path(path)
    if not p.is_file():
        return None
    for i, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").split("\n"), 1):
        if ln.startswith(str(ref) + ",") or ln.startswith('"' + str(ref) + '"'):
            return i
    return None


def _json_line(path, needle):
    p = pathlib.Path(path)
    if not p.is_file():
        return None
    for i, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").split("\n"), 1):
        if needle in ln:
            return i
    return None


def _ev(path, line=None):
    return f"{path}:L{line}" if line else path


def _g_rel(p):
    """`Gemma/x/y` (curated evidence style) -> `x/y` (relative to the Gemma root)."""
    return p[len("Gemma/"):] if p.startswith("Gemma/") else p


def render(g, fp12, cl, baseline, lb_src, lb_best, steering, conflicts, rows, scorer_ref,
           pulled_attr, gold_cov=None):
    g = pathlib.Path(g)
    kb = g / "kb"
    head = ["# STANDING_TRUTHS (generated by build_kb.py; do not edit)",
            f"Inputs fingerprint {fp12}. Bullets: `- [id] statement — evidence: <path>:L<n> "
            "(<status>)`; paths are relative to the Gemma root. Sources: curated SUPPORTED "
            "claims, SUPPORTED non-superseded log verdicts, the newest unit of each correction "
            "chain, builder-measured facts. Nothing here is adopted as policy."]
    # ---------------------------------------------------------------- Baselines & LB
    base = []
    if steering.get("found"):
        base.append(f"- [B-steering] steering file says {steering['label']} @ {steering['score']:.2f} "
                    f"(ref {steering['ref']}) — evidence: ../.kiro/steering/gemma-submission-protocol.md"
                    f":L{steering['line']} (MEASURED)")
    if baseline:
        ln = _json_line(kb / "curated" / "run_labels.json", '"baseline"')
        base.append(f"- [B-curated] curated policy baseline {baseline.get('label')} @ "
                    f"{baseline.get('lb')} (ref {baseline.get('submission_ref')}) — evidence: "
                    f"{_ev('kb/curated/run_labels.json', ln)} (MEASURED)")
    src_rel = "kb/" + lb_src["path"]
    for t in ("main", "small-model", "dev-proxy"):
        b = lb_best.get(t)
        if not b:
            continue
        ln = _csv_line(lb_src["abs"], b["ref"])
        base.append(f"- [B-lb-{t}] LB best {t} track: {b['desc']} @ {b['score']:.2f} (ref {b['ref']}, "
                    f"{b['date'][:10]}) — evidence: {_ev(src_rel, ln)} (MEASURED)")
    for i, c in enumerate(conflicts, 1):
        base.append(f"- [B-conflict-{i}] BASELINE CONFLICT: {c} — not adopted; the user decides — "
                    f"evidence: {src_rel} (MEASURED)")
    # ---------------------------------------------------------------------- Stacks
    stacks = []
    plat = Counter((r.get("stack") or {}).get("platform") or "unknown" for r in rows)
    trk = Counter(r.get("track") or "unknown" for r in rows)
    stacks.append("- [S-rows] runs.jsonl rows by stack: " + ", ".join(f"{k} {v}" for k, v in sorted(plat.items()))
                  + "; by track: " + ", ".join(f"{k} {v}" for k, v in sorted(trk.items()))
                  + " (tracks are never pooled) — evidence: kb/runs.jsonl (MEASURED)")
    unver = sum(1 for r in rows if (r.get("stack") or {}).get("platform") in ("local-rig", "local-sweep")
                and not (r.get("stack") or {}).get("model_served_verified"))
    stacks.append(f"- [S-served] the served model is NOT verified on local stacks: {unver} local-rig/"
                  f"local-sweep rows carry model_served_verified=false — evidence: kb/runs.jsonl (MEASURED)")
    dh_runs = {}
    for r in rows:
        dh = r.get("dev_harness") or {}
        if dh.get("found"):
            dh_runs[r["run_id"]] = (dh.get("matches_scorer"), dh.get("compaction_interval"))
    if scorer_ref:
        m = Counter(v[0] for v in dh_runs.values())
        vals = Counter(v[1] for v in dh_runs.values() if v[0] is False)
        src = scorer_ref.get("source", "comp_files/HARNESS_README.md")
        stacks.append(f"- [S-devharness] scorer compaction_interval={scorer_ref.get('compaction_interval')}; "
                      f"runs with a parsed notebook: {m.get(True, 0)} match, {m.get(False, 0)} mismatch "
                      f"(compaction_interval values {dict(sorted((str(k), v) for k, v in vals.items()))}), "
                      f"{m.get(None, 0)} unknown — evidence: {src} (MEASURED)")
    flags = Counter()
    example = None
    for a in pulled_attr or []:
        for pr in a.get("per_ref") or []:
            d = pr.get("detail", "")
            f = d.split(":", 1)[0].split(" ", 1)[0] if d else "?"
            flags[f] += 1
            if example is None and "MISMATCH" in f:
                example = (a["run_id"], pr["ref"], d)
    if pulled_attr:
        ex = (f"; e.g. {example[0]} vs ref {example[1]}: {_one(example[2], 90)}" if example else "")
        stacks.append(f"- [S-pulls] `kernels output` returns the latest version only; pulled runs "
                      f"{len(pulled_attr)}, attribution flags {dict(sorted(flags.items()))}{ex} — evidence: "
                      f"{example[0] if example else 'kb/pulled'} (MEASURED)")
    gc_path = kb / "replays" / "gold_coverage.json"
    if gold_cov is None and gc_path.is_file():
        try:
            gold_cov = json.loads(gc_path.read_text(encoding="utf-8"))
        except ValueError:
            gold_cov = None
    if gold_cov:
        recs = gold_cov.get("rows") if isinstance(gold_cov, dict) else gold_cov
        cnt = Counter((x.get("verdict") or x.get("gold_first") or "?") for x in (recs or []))
        stacks.append(f"- [S-gold] gold-first coverage: {dict(sorted(cnt.items()))} — evidence: "
                      f"kb/replays/gold_coverage.json (MEASURED)")
    else:
        ga = kb / "replays" / "goldgate_all.json"
        if ga.is_file():
            try:
                d = json.loads(ga.read_text(encoding="utf-8"))
                recs = d.get("results") if isinstance(d, dict) and "results" in d else d
                if isinstance(recs, dict):
                    recs = list(recs.values())
                cnt = Counter((x.get("gold_first") or "?") for x in recs if isinstance(x, dict))
                if cnt:
                    stacks.append(f"- [S-gold] gold-first coverage (rp-4, written by local_eval/"
                                  f"gold_gate_all.py): {dict(sorted(cnt.items()))} — evidence: "
                                  f"kb/replays/goldgate_all.json (MEASURED)")
            except (ValueError, AttributeError):
                pass
    # ------------------------------------------------------------ closed / open axes
    closed, opened = [], []
    for c in cl.get("curated") or []:
        if c.get("status") != "SUPPORTED" or not c.get("evidence_ok"):
            continue
        evs = [e for e in c.get("evidence") or [] if e.get("path") and e.get("exists")]
        p = next((e for e in evs if e.get("line")), evs[0] if evs else None)
        ev = (_ev(_g_rel(p["path"]), p.get("line")) if p
              else _ev("kb/curated/claims.jsonl", c.get("curated_line")))
        stmt = _one(c["text"])
        line = f"- [{c['id']}] {stmt} — evidence: {ev} (SUPPORTED, curated)"
        (closed if _CLOSED.search(stmt) else opened).append(line)
    log_closed, log_open = [], []
    for c in sorted(cl.get("claims") or [], key=lambda x: (-x["line"], x["claim_id"])):
        if c.get("status") != "SUPPORTED":
            continue
        # verdict / standing-truth claims only (never table rows or bare fact-lines)
        if not (c["kind"] == "standing-truth"
                or (c["kind"] in ("heading", "verdict") and c.get("unit_kind") == "verdict")):
            continue
        stmt = _one(c["text"])
        line = (f"- [{c['claim_id']}] {stmt} — evidence: GEMMA_EXPERIMENT_LOG.md:"
                f"L{c['line']} (SUPPORTED)")
        if _CLOSED.search(stmt):
            log_closed.append(line)
        elif _OPEN.search(stmt):
            log_open.append(line)
    # --------------------------------------------------------------- corrections
    corr = []
    for ch in sorted(cl.get("chains") or [], key=lambda x: -x["newest_line"]):
        if ch.get("newest_superseded"):
            continue
        olds = [f"L{x}" for x in ch["lines"][:-1]]
        corr.append(f"- [{ch['newest']}] {_one(ch['newest_heading'], 150)} — evidence: "
                    f"GEMMA_EXPERIMENT_LOG.md:L{ch['newest_line']} (CORRECTION; supersedes "
                    f"{', '.join(olds) or 'its own tagged heading'})")

    def assemble(nc, no, ncorr):
        out = list(head)
        out += ["", "## Baselines & LB"] + (base or ["- [B-none] no baseline facts — evidence: "
                                                    "kb/curated/run_labels.json (MEASURED)"])
        out += ["", "## Stacks"] + stacks
        cl_lines = (closed + log_closed)[:nc]
        op_lines = (opened + log_open)[:no]
        out += ["", "## Closed axes"] + (cl_lines or ["- [none] no SUPPORTED closed-axis claim — "
                                                       "evidence: kb/log_claims.md (MEASURED)"])
        out += ["", "## Open axes"] + (op_lines or ["- [none] no SUPPORTED open-axis claim — "
                                                     "evidence: kb/log_claims.md (MEASURED)"])
        out += ["", "## Corrections (newest unit of each chain)"] + (
            corr[:ncorr] or ["- [none] no correction chain — evidence: kb/log_claims.md (MEASURED)"])
        hidden = (len(closed + log_closed) - len(cl_lines)) + (len(opened + log_open) - len(op_lines)) \
            + (len(corr) - len(corr[:ncorr]))
        if hidden > 0:
            out.append(f"- [trimmed] {hidden} more bullet(s) omitted to stay <= {MAX_LINES} lines — "
                       f"evidence: kb/log_claims.md (MEASURED)")
        return out

    nc, no, ncorr = 14, 10, 20
    out = assemble(nc, no, ncorr)
    while len(out) > MAX_LINES and (nc or no or ncorr):
        if no > 2:
            no -= 1
        elif ncorr > 4:
            ncorr -= 1
        elif nc > 2:
            nc -= 1
        else:
            break
        out = assemble(nc, no, ncorr)
    return "\n".join(out[:MAX_LINES]) + "\n"
