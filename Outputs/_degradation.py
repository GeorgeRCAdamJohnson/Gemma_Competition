"""Do solves get worse the longer a run goes? (user hypothesis: a caching or server-state effect over repeated runs)

Every outcome is task-adjusted: residual = resolved - mean resolved for that task over all E4B attempts, so a round
or time bin that happened to hold harder tasks does not look worse.
A. By round number, within each experiment with >= 3 rounds (rounds are sequential in Colab runs and interleaved
   on one server lifetime in Kaggle runs): per-round mean residual and a per-experiment slope.
B. By server age (attempts linked to a vLLM server): minutes from server start to attempt start, in bins; with the
   server's prefix-cache hit rate and KV usage at that time.
C. By prefix-cache hit rate at attempt start.
Writes Outputs/DEGRADATION.md."""
import bisect
import math
import sqlite3
from collections import defaultdict
from pathlib import Path

db = sqlite3.connect("kb/attempts.sqlite")
q = lambda s, *a: db.execute(s, a).fetchall()
task_mean = dict(q("""SELECT task, AVG(resolved) FROM attempts_unique
                      WHERE model NOT LIKE '%31b%' AND resolved IS NOT NULL GROUP BY task"""))


def summary(values):
    n = len(values)
    if n < 2:
        return n, None, None
    mean = sum(values) / n
    sd = math.sqrt(sum((v - mean) ** 2 for v in values) / (n - 1))
    return n, mean, mean / (sd / math.sqrt(n)) if sd else 0.0


def slope(points):
    n = len(points)
    mx = sum(x for x, _ in points) / n
    my = sum(y for _, y in points) / n
    sxx = sum((x - mx) ** 2 for x, _ in points)
    if not sxx:
        return None, None
    b = sum((x - mx) * (y - my) for x, y in points) / sxx
    resid = [y - my - b * (x - mx) for x, y in points]
    se = math.sqrt(sum(r * r for r in resid) / (n - 2) / sxx) if n > 2 else None
    return b, (b / se if se else None)


md = ["# Do solves degrade over repeated runs?\n",
      "Generated by `Outputs/_degradation.py`. Outcomes are task-adjusted (attempt minus its task's E4B mean), in "
      "percentage points. z is rough (attempts cluster by task and round).\n"]

# A. round number within experiment
rows = q("""SELECT exp, round, task, resolved FROM attempts_unique
            WHERE model NOT LIKE '%31b%' AND resolved IS NOT NULL AND round IS NOT NULL""")
by_exp = defaultdict(list)
for exp, rnd, task, res in rows:
    try:
        by_exp[exp].append((int(rnd), res - task_mean[task]))
    except (TypeError, ValueError):
        pass
pooled = defaultdict(list)
md += ["## A. By round number (experiments with >= 3 rounds)\n",
       "| experiment | rounds | attempts | slope per round | z | round 1 | last round |", "|---|---|---|---|---|---|---|"]
slopes = []
for exp, pts in sorted(by_exp.items()):
    rounds = sorted({r for r, _ in pts})
    if len(rounds) < 3 or len(pts) < 60:
        continue
    b, z = slope(pts)
    first = summary([y for r, y in pts if r == rounds[0]])[1]
    last = summary([y for r, y in pts if r == rounds[-1]])[1]
    slopes.append((exp, b, z, len(pts)))
    for r, y in pts:
        pooled[r - rounds[0] + 1].append(y)
    md.append(f"| {exp} | {len(rounds)} | {len(pts)} | {100 * b:+.2f} | {z:+.1f} | {100 * first:+.1f} | {100 * last:+.1f} |")
neg = sum(b < 0 for _, b, _, _ in slopes)
md += ["", f"Experiments with a negative slope: {neg} of {len(slopes)}. Strongly negative (z <= -2): "
       f"{sum(1 for _, b, z, _ in slopes if z is not None and z <= -2)}; strongly positive (z >= 2): "
       f"{sum(1 for _, b, z, _ in slopes if z is not None and z >= 2)}.\n",
       "Pooled by round position (1 = each experiment's first round):\n",
       "| round position | attempts | mean residual | z |", "|---|---|---|---|"]
for r in sorted(pooled):
    n, m, z = summary(pooled[r])
    if n >= 30:
        md.append(f"| {r} | {n} | {100 * m:+.1f} | {z:+.1f} |")

# B/C. server age and cache state at attempt start
servers = {sid: (exp, first) for sid, exp, first in q("SELECT server_id, exp, first_ts FROM vllm_servers")}
metrics = defaultdict(list)
for sid, ts, kv, hit in q("SELECT server_id, ts, kv_usage, prefix_hit FROM vllm_metrics ORDER BY server_id, ts"):
    metrics[sid].append((ts, kv, hit))
stamps = {sid: [m[0] for m in ms] for sid, ms in metrics.items()}
linked = q("""SELECT l.server_id, a.task, a.resolved, t.first_ts FROM attempt_server_load l
              JOIN attempts_unique a ON a.id = l.attempt_id JOIN traces t ON t.attempt_id = a.id
              WHERE a.resolved IS NOT NULL AND t.first_ts IS NOT NULL AND a.model NOT LIKE '%31b%'""")
age_bins = defaultdict(list)
hit_bins = defaultdict(list)
state = defaultdict(lambda: [[], []])
for sid, task, res, start in linked:
    exp, first = servers[sid]
    age = (start - first) / 60
    if age < 0:
        continue
    b = min(int(age // 30) * 30, 180)
    age_bins[b].append(res - task_mean[task])
    i = bisect.bisect_right(stamps.get(sid, []), start) - 1
    if i >= 0:
        _, kv, hit = metrics[sid][i]
        state[b][0].append(hit)
        state[b][1].append(kv)
        hit_bins[min(int(hit // 10) * 10, 80) if hit is not None else None].append(res - task_mean[task])
md += ["", f"## B. By server age at attempt start ({len(linked)} linked attempts, {len(metrics)} servers)\n",
       "| minutes since server start | attempts | mean residual | z | prefix hit % | KV usage % |",
       "|---|---|---|---|---|---|"]
for b in sorted(age_bins):
    n, m, z = summary(age_bins[b])
    if m is None:
        continue
    hits, kvs = state[b]
    label = f"{b}-{b + 30}" if b < 180 else "180+"
    md.append(f"| {label} | {n} | {100 * m:+.1f} | {z:+.1f} | "
              f"{sum(hits) / len(hits):.1f} | {sum(kvs) / len(kvs):.1f} |" if hits else
              f"| {label} | {n} | {100 * m:+.1f} | {z:+.1f} | - | - |")
md += ["", "## C. By prefix-cache hit rate at attempt start\n", "| prefix hit % | attempts | mean residual | z |",
       "|---|---|---|---|"]
for b in sorted(k for k in hit_bins if k is not None):
    n, m, z = summary(hit_bins[b])
    if m is None:
        continue
    md.append(f"| {b}-{b + 10} | {n} | {100 * m:+.1f} | {z:+.1f} |")
Path("Outputs/DEGRADATION.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
