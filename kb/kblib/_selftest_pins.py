#!/usr/bin/env python3
"""Self-test for the per-task dependency-pin parser/resolver (rp-4).

Stdlib only. Exercises `_parse_lock_pins`, `_resolve_pins` (non-rich -> empty,
rich lockfile -> lockfile provenance, rich empty-worktree -> hardcoded fallback)
WITHOUT installing anything or touching the base env. Run:

    python Gemma/kb/kblib/_selftest_pins.py

Exits 0 and prints `PIN SELFTEST OK` on success.
"""
from __future__ import annotations

import pathlib
import sys
import tempfile

_HERE = pathlib.Path(__file__).resolve().parent
if str(_HERE.parent) not in sys.path:
    sys.path.insert(0, str(_HERE.parent))

from kblib import replay  # noqa: E402

_FIXTURE_LOCK = """\
# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "markdown-it-py"
version = "3.0.0"
description = "Python port of markdown-it."
optional = false

[[package]]
name = "Pygments"
version = "2.19.2"
description = "Pygments is a syntax highlighting package."
optional = false

[[package]]
name = "some-other-dep"
version = "1.2.3"
description = "irrelevant"
optional = false
"""


def _write_lock(dirpath, text):
    (pathlib.Path(dirpath) / "poetry.lock").write_text(text, encoding="utf-8")


def main():
    with tempfile.TemporaryDirectory(prefix="gkb_pinselftest_") as td:
        # 1. parser extracts pygments + markdown-it-py, normalizing case/dashes
        _write_lock(td, _FIXTURE_LOCK)
        pins = replay._parse_lock_pins(td)
        assert pins.get("pygments") == "2.19.2", pins
        assert pins.get("markdown-it-py") == "3.0.0", pins
        assert "some-other-dep" not in pins, pins
        print("parse: pygments==2.19.2, markdown-it-py==3.0.0 OK")

        # 2. non-rich repo -> no pins at all (byte-identical to pre-fix engine)
        p, prov, warns = replay._resolve_pins("psf/requests", "requests_1", td)
        assert p == {} and prov == "none" and warns == [], (p, prov, warns)
        print("resolve(non-rich): ({}, 'none', []) OK")

        # 3. rich with a parseable lock -> lockfile provenance
        p, prov, warns = replay._resolve_pins("Textualize/rich", "rich_4070", td)
        assert prov == "lockfile", (p, prov)
        assert p.get("pygments") == "2.19.2", p
        assert warns == [], warns
        print("resolve(rich, lockfile): provenance=lockfile OK")

        # 4. missing lock -> empty parse
        with tempfile.TemporaryDirectory(prefix="gkb_pinselftest_empty_") as empty:
            assert replay._parse_lock_pins(empty) == {}
            # rich + empty worktree + known task -> hardcoded FALLBACK
            p, prov, warns = replay._resolve_pins("Textualize/rich", "rich_3469", empty)
            assert prov == "fallback", (p, prov)
            assert p.get("pygments") == "2.17.2", p
            assert warns and "FALLBACK" in warns[0], warns
            print("resolve(rich, empty worktree): provenance=fallback (2.17.2) OK")

            # rich + empty worktree + unknown task -> no pins, provenance none
            p, prov, warns = replay._resolve_pins("Textualize/rich", "rich_9999", empty)
            assert p == {} and prov == "none", (p, prov)
            print("resolve(rich, unknown task): ({}, 'none', []) OK")

    print("PIN SELFTEST OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
