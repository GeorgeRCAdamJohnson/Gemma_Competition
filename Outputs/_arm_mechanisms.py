"""Task-adjusted mechanism effects for every E4B arm (exp x arm) with traced attempts.

For each attempt and metric, residual = value - mean of that metric over all traced E4B attempts on the same task.
An arm's effect is its mean residual, so arms that ran easier tasks don't look better. z = effect / (sd / sqrt(n)) is
rough: attempts on the same task/round are not independent and there are many arms, so only |z| >= 3 is flagged.
Metrics: solve; first_gold (first edit on a gold file); convert (solve given first edit on gold: right-file conversion);
wrong_file (edited, never a gold file); overflow; no_edit; calls; recurring_wrong (patch is in its task's most common
losing fix family, hard + swing tasks only). Writes Outputs/ARM_MECHANISMS.md."""
import hashlib
import json
import math
import re
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, "kb/attemptdb")
from vfs import VFS  # noqa: E402

db = sqlite3.connect("kb/attempts.sqlite")
vfs = VFS(roots=("Outputs",))
rows = db.execute("""
    SELECT a.exp, a.arm, a.task, a.resolved, a.error_class, a.patch_path, f.first_edit_gold, f.edited_any_gold,
           f.n_edit_ok, f.n_calls
    FROM attempts_unique a JOIN attempt_features f ON f.attempt_id = a.id AND f.basis = 'trace'
    WHERE a.model NOT LIKE '%31b%' AND a.resolved IS NOT NULL""").fetchall()


def family(patch):
    adds = sorted({re.sub(r"\s+", " ", l[1:].strip()) for l in patch.splitlines()
                   if l.startswith("+") and not l.startswith("+++") and l[1:].strip()})
    files = sorted(set(re.findall(r"^\+\+\+ b/(\S+)", patch, re.M)))
    return hashlib.sha1(("|".join(files) + "||" + "\n".join(adds)).encode()).hexdigest()[:10]


# each hard/swing task's most common losing fix family
dossiers = {}
for name in ("hard", "swing"):
    path = Path(f"Outputs/{name}_dossier.json")
    if path.is_file():
        dossiers.update(json.loads(path.read_text()))
fam_of = {}
losing = defaultdict(lambda: defaultdict(int))
for exp, arm, task, res, ec, pp, *_ in rows:
    if task in dossiers and pp and vfs.exists(pp):
        text = vfs.text(pp)
        if text.strip():
            fam_of[pp] = family(text)
            if not res:
                losing[task][fam_of[pp]] += 1
top_losing = {t: max(c, key=c.get) for t, c in losing.items() if c}

records = []
for exp, arm, task, res, ec, pp, feg, eag, nok, nc in rows:
    m = {"solve": res, "first_gold": int(bool(feg)), "wrong_file": int(bool(nok) and not eag),
         "overflow": int(ec == "overflow"), "no_edit": int(not nok), "calls": nc or 0}
    if feg:
        m["convert"] = res
    if task in top_losing and pp in fam_of:
        m["recurring_wrong"] = int(fam_of[pp] == top_losing[task])
    records.append((exp, arm, task, m))

metrics = ["solve", "first_gold", "convert", "wrong_file", "overflow", "no_edit", "calls", "recurring_wrong"]
task_mean = {}
for k in metrics:
    acc = defaultdict(list)
    for _, _, task, m in records:
        if k in m:
            acc[task].append(m[k])
    task_mean[k] = {t: sum(v) / len(v) for t, v in acc.items()}

arms = defaultdict(lambda: defaultdict(list))
tasks_of = defaultdict(set)
for exp, arm, task, m in records:
    tasks_of[(exp, arm)].add(task)
    for k in metrics:
        if k in m:
            arms[(exp, arm)][k].append(m[k] - task_mean[k][task])

catalog = {(e, a): c for e, a, c in db.execute("SELECT exp, arm, changed_vs_pack1 FROM arm_catalog")}
out = []
for key, res in arms.items():
    n = len(res["solve"])
    if n < 60 or len(tasks_of[key]) < 10:
        continue
    row = {"exp": key[0], "arm": key[1], "n": n, "tasks": len(tasks_of[key])}
    for k in metrics:
        v = res.get(k, [])
        if len(v) < 20:
            row[k] = None
            continue
        mean = sum(v) / len(v)
        sd = math.sqrt(sum((x - mean) ** 2 for x in v) / (len(v) - 1)) or 1e-9
        row[k] = (mean, mean / (sd / math.sqrt(len(v))), len(v))
    row["changed"] = catalog.get(key)
    out.append(row)


def cell(x, scale=100, unit=""):
    if x is None:
        return "-"
    mean, z, _ = x
    flag = " **" if abs(z) >= 3 else ""
    return f"{mean * scale:+.1f}{unit} (z {z:+.1f}){flag}"


lines = ["# Task-adjusted mechanism effects per E4B arm\n",
         "Generated by `Outputs/_arm_mechanisms.py`. Each value is the arm's mean difference from the same task's "
         "average over all traced E4B attempts (percentage points; calls in calls). ** = |z| >= 3 (rough; attempts "
         "are clustered and there are many arms). `convert` = solve rate given a first edit on a gold file. "
         "`recurring` = share of patches in the task's most common losing fix (hard + swing tasks).\n",
         "| exp | arm | n | tasks | solve | first gold | convert | wrong file | overflow | no edit | calls | recurring |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in sorted(out, key=lambda r: -(r["solve"][0] if r["solve"] else 0)):
    lines.append(f"| {r['exp']} | {r['arm']} | {r['n']} | {r['tasks']} | {cell(r['solve'])} | {cell(r['first_gold'])} | "
                 f"{cell(r['convert'])} | {cell(r['wrong_file'])} | {cell(r['overflow'])} | {cell(r['no_edit'])} | "
                 f"{cell(r['calls'], 1)} | {cell(r['recurring_wrong'])} |")
Path("Outputs/ARM_MECHANISMS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
Path("Outputs/arm_mechanisms.json").write_text(json.dumps(out, indent=1, default=str))

print(f"{len(out)} arms (n >= 60, >= 10 tasks), {len(records)} traced attempts\n")
for k in metrics:
    flagged = [r for r in out if r[k] and abs(r[k][1]) >= 3]
    flagged.sort(key=lambda r: -r[k][1])
    print(f"{k}: {len(flagged)} arms with |z| >= 3")
    for r in flagged[:6] + (flagged[-4:] if len(flagged) > 10 else []):
        scale = 1 if k == "calls" else 100
        print(f"   {str(r['exp'])[:44]:44s} {str(r['arm'])[:22]:22s} n {r['n']:4d}  {r[k][0] * scale:+6.1f}  z {r[k][1]:+5.1f}  "
              f"solve {r['solve'][0] * 100:+5.1f}  changed {str(r['changed'])[:70]}")
